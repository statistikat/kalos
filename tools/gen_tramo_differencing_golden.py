#!/usr/bin/env python3
"""Generate tests/jvm_tramo_differencing.h from the item 23-C tramo
differencing-decision corpus (validation/evidence/native/tramo-differencing,
captured through the observer TramoDifferencingDecisionProbe.java against the
pinned jdplus 3.9.0 jars; double capture, byte-identical csv files across JVM
processes, class-load witnesses under loadlog-*.txt).

The golden is the captured LINE GRAMMAR itself: the oracle protocol header
(DIFF/BAT), the JVM-echoed module facts (diff_result, diff_info, after,
panel, mspec, lastmodel) and the raw IEEE-754 bits of each case series. The
DIFF/BAT header fields carry the request (orders d,bd,p,q,bp,bq; mean;
cancel/ub1/ub2/eps; the initial-round flag). The replay layer
(tests/test_tramo_differencing.cpp) drives kalos::decide_tramo_differencing
from the header tokens and compares every module-level fact line
bit-pattern-for-bit-pattern; the battery-stage facts of the BAT cases
(init, cleanup, estimate, ladder, peaks, over, step, seas1, seas2, final)
and the FULL-kernel facts ride along as pinned landing facts for the
23-C.2 battery-replay unit and are not asserted here. Regenerate with:
  python3 tools/gen_tramo_differencing_golden.py \
      validation/evidence/native/tramo-differencing tests/jvm_tramo_differencing.h
"""
import csv
import os
import struct
import sys

NAN_BITS = 0x7FF8000000000000

# Module-level facts the replay asserts; everything else the observer
# captured is battery/kernel landing material.
MODULE_KEYS = ("diff_result", "diff_info", "after", "panel", "mspec", "lastmodel")


def cstr(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % o)
    out.append('"')
    return "".join(out)


def value_bits(tok):
    if tok == "nan":
        return NAN_BITS
    return struct.unpack(">Q", struct.pack(">d", float(tok)))[0]


def yes(tok):
    return 1 if tok == "y" else 0


def main(corpus_dir, dst):
    headers = {}   # id -> header tokens
    series = {}    # id -> bits
    order = []
    with open(os.path.join(corpus_dir, "inputs.csv")) as f:
        for r in csv.DictReader(f):
            line = r["line"]
            if line.startswith("req "):
                continue
            tok = line.split(" ")
            cid = r["id"]
            if tok[0] in ("DIFF", "BAT", "FULL"):
                if cid not in headers:
                    headers[cid] = tok
                    order.append(cid)
            elif tok[0] == "values":
                series[cid] = [value_bits(t) for t in tok[1:]]

    facts = {}     # id -> list of (key, value) in capture order
    with open(os.path.join(corpus_dir, "diff-facts.csv")) as f:
        for r in csv.DictReader(f):
            facts.setdefault(r["id"], []).append((r["key"], r["value"]))

    meta = {}
    with open(os.path.join(corpus_dir, "metadata.R")) as f:
        for line in f:
            if " <- " in line:
                k, v = line.strip().split(" <- ", 1)
                meta[k] = v.strip().strip('"')

    out = []
    out.append("// Generated by tools/gen_tramo_differencing_golden.py - do not edit.")
    out.append("// Item 23-C tramo differencing-decision golden: the live round-1")
    out.append("// tramo.internal.DifferencingModule facts captured through")
    out.append("// validation/reference/TramoDifferencingDecisionProbe.java from the")
    out.append("// pinned jdplus 3.9.0 jars (corpus "
               "validation/evidence/native/tramo-differencing, double capture byte-identical).")
    out.append("// probe_sha256 = %s" % meta.get("probe_sha256", "?"))
    out.append("// jvm = %s (%s)" % (meta.get("jvm_version", "?"), meta.get("jvm_vendor", "?")))
    out.append("// MODULE_KEYS lines are replayed by tests/test_tramo_differencing.cpp;")
    out.append("// stage lines are the battery/kernel landing facts pinned for 23-C.2/23-F.")
    out.append("#ifndef KALOS_TESTS_JVM_TRAMO_DIFFERENCING_H")
    out.append("#define KALOS_TESTS_JVM_TRAMO_DIFFERENCING_H")
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace kalos::test {")
    out.append("")
    out.append("struct TdCase {")
    out.append("    const char* id;")
    out.append("    const char* mode;   // DIFF | BAT (replayed) | FULL (landing only)")
    out.append("    int period;")
    out.append("    int seasonal;       // module seasonal flag (also maxbd = seasonal)")
    out.append("    int log_input;      // description log flag (regarima y = ln(series))")
    out.append("    int d0, bd0, p0, q0, bp0, bq0;  // entry description orders")
    out.append("    int mean0;          // entry description mean flag")
    out.append("    double cancel, ub1, ub2, eps;")
    out.append("    int initial;        // module initial flag (round-1 request)")
    out.append("    const std::uint64_t* series_bits;")
    out.append("    std::size_t series_len;")
    out.append("    const char* const* expect;      // module-level fact lines")
    out.append("    std::size_t expect_len;")
    out.append("    const char* const* stage;       // battery/kernel landing facts")
    out.append("    std::size_t stage_len;")
    out.append("};")
    out.append("")

    n_series = 0
    for cid in order:
        tok = headers[cid]
        bits = series[cid]
        expect = [k + " " + v for k, v in facts.get(cid, []) if k in MODULE_KEYS]
        stage = [k + " " + v for k, v in facts.get(cid, []) if k not in MODULE_KEYS]
        mode = tok[0]
        if mode in ("DIFF", "BAT"):
            if mode == "DIFF":
                period, seasonal, mean, initial = int(tok[2]), yes(tok[3]), yes(tok[11]), yes(tok[16])
                log_input = yes(tok[4])
                d0, bd0, p0, q0, bp0, bq0 = (int(tok[i]) for i in range(5, 11))
                cancel, ub1, ub2, eps = (float(tok[i]) for i in range(12, 16))
            else:
                period, seasonal, mean, initial = int(tok[2]), yes(tok[3]), yes(tok[12]), yes(tok[18])
                log_input = yes(tok[5])
                d0, bd0, p0, q0, bp0, bq0 = (int(tok[i]) for i in range(6, 12))
                cancel, ub1, ub2, eps = (float(tok[i]) for i in range(13, 17))
            out.append("static const std::uint64_t kTdSeries%d[] = {%s};" % (
                n_series, ", ".join("0x%016xULL" % b for b in bits)))
            n_series += 1
            for name, lines in (("Exp", expect), ("Stg", stage)):
                if lines:
                    out.append("static const char* const kTd%s%s[] = {" % (name, cid))
                    for ln in lines:
                        out.append("    %s," % cstr(ln))
                    out.append("};")
            out.append("// %s: %s n=%d" % (mode, cid, len(bits)))
            out.append("static const TdCase kTdCase_%s = {" % cid)
            out.append("    %s, %s, %d, %d, %d," % (cstr(cid), cstr(mode), period, seasonal,
                log_input))
            out.append("    %d, %d, %d, %d, %d, %d, %d," % (d0, bd0, p0, q0, bp0, bq0, mean))
            out.append("    %.17g, %.17g, %.17g, %.17g, %d," % (cancel, ub1, ub2, eps, initial))
            out.append("    kTdSeries%d, %d," % (n_series - 1, len(bits)))
            out.append("    %s, %d, %s, %d," % (
                ("kTdExp%s" % cid) if expect else "nullptr", len(expect),
                ("kTdStg%s" % cid) if stage else "nullptr", len(stage)))
            out.append("};")
            out.append("")

    out.append("inline const TdCase* td_cases(std::size_t& count)")
    out.append("{")
    out.append("    static const TdCase kAll[] = {")
    ids = [c for c in order if headers[c][0] in ("DIFF", "BAT")]
    out.append("        " + ", ".join("kTdCase_%s" % c for c in ids) + ",")
    out.append("    };")
    out.append("    count = %d;" % len(ids))
    out.append("    return kAll;")
    out.append("}")
    out.append("")
    out.append("} // namespace kalos::test")
    out.append("")
    out.append("#endif // KALOS_TESTS_JVM_TRAMO_DIFFERENCING_H")
    out.append("")

    with open(dst, "w") as f:
        f.write("\n".join(out))
    print("wrote %s (%d cases)" % (dst, len(ids)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
