#!/usr/bin/env python3
"""Generate tests/jvm_decompose_ucarima.h from the item 24-B
decompose-ucarima corpus (validation/evidence/native/decompose-ucarima,
captured by validation/reference/capture-decompose-ucarima.R through the
observer DecomposeUcarimaProbe.java against the pinned jdplus 3.9.0 jars;
double capture, byte-identical csv files across JVM processes).

The golden carries, per case, the JVM-echoed request block (req lines) and
the DECOMPOSITION-SEAM fact grammar the unit mirrors: the d.decompose state,
the d block (count/valid, the SarimaModel "model" rows, every "cN" component
row incl. the per-getter maerr/varr/sfdr failure lines), the cmp block
(SeatsModel.compactUcarimaModel(false, false)), the r block (raw selector
chain), and the deterministic "status error:...SeatsException:Invalid
decomposition" line the kernel throws before estimation whenever d came back
null under mode None. Refusal cases (the 16 Legacy approximation_required
requests, the 1 Noisy request) carry no facts: the unit fails closed with a
pinned reason BEFORE the seam, asserted through the refusal code + message.

Out of scope and NOT emitted (see docs/contracts/decompose-ucarima-contract.md):
the k.* kernel flags, the "status ok"/Eco/MatrixException statuses (products
of the estimation machinery past this seam), the toolkit/vtpl/evt records.

Regenerate with:
  python3 tools/gen_decompose_ucarima_golden.py \
      validation/evidence/native/decompose-ucarima tests/jvm_decompose_ucarima.h
"""
import csv
import os
import sys

# The pinned refusal reasons (src/decompose_ucarima.cpp); index = refusal code.
REASONS = [
    "",
    "decompose_ucarima: approximation_required decision is outside the D6 "
    "envelope",
    "decompose_ucarima: Noisy approximation mode is outside the D6 envelope",
]

SEAM_KEYS = ("d.decompose", "d.excep", "d", "cmp.excep", "cmp", "r.decompose",
             "r.count", "r", "r.excep")
SEATS_INVALID = ("error:jdplus.tramoseats.base.api.seats.SeatsException:"
                 "Invalid decomposition")


def cstr(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % o)
    out.append('"')
    return "".join(out)


def main(corpus_dir, dst):
    cases, order = {}, []
    with open(os.path.join(corpus_dir, "cases.csv")) as f:
        for r in csv.DictReader(f):
            cases[r["id"]] = r
            order.append(r["id"])
    req = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "inputs.csv")) as f:
        for r in csv.DictReader(f):
            if r["line"].startswith("req "):
                req[r["id"]].append(r["line"])
    facts = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "model-facts.csv")) as f:
        for r in csv.DictReader(f):
            key, val = r["key"], r["value"]
            if key in SEAM_KEYS:
                facts[r["id"]].append(key + " " + val)
            elif key == "status" and val == SEATS_INVALID:
                facts[r["id"]].append(key + " " + val)

    out = []
    out.append("// Generated by tools/gen_decompose_ucarima_golden.py - do not edit.")
    out.append("// Item 24-B decompose-ucarima golden: the double-captured JVM corpus")
    out.append("// (validation/evidence/native/decompose-ucarima) as request-echo plus the")
    out.append("// decomposition-seam fact grammar (d/cmp/r blocks, the d-null SeatsException")
    out.append("// status line). Refusal cases (16 approximation_required, 1 Noisy) carry no")
    out.append("// facts: the unit fails closed with the pinned reason. Record-only facts")
    out.append("// (k.*, status ok/Eco/Matrix, toolkit, tpl, evt) stay in the csv corpus.")
    out.append("#ifndef KALOS_TESTS_JVM_DECOMPOSE_UCARIMA_H")
    out.append("#define KALOS_TESTS_JVM_DECOMPOSE_UCARIMA_H")
    out.append("")
    out.append("#include <cstddef>")
    out.append("")
    out.append("namespace golden_du {")
    out.append("")
    out.append("struct Case {")
    out.append("    const char* id;")
    out.append("    int refusal;   // 0 none, 1 approximation_required, 2 Noisy")
    out.append("    const char* reason;  // pinned refusal message (\"\" when refusal == 0)")
    out.append("    std::size_t nreq;")
    out.append("    const char* const* req;")
    out.append("    std::size_t nfacts;")
    out.append("    const char* const* facts;")
    out.append("};")
    out.append("")

    def arr(name, items):
        out.append("inline const char* k_%s[] = {" % name)
        if not items:
            # zero-size arrays are not valid C++; the table entry pairs the
            # pointer with length 0, so this sentinel element is never read.
            out.append('    "",')
        for it in items:
            out.append("    %s," % cstr(it))
        out.append("};")
        out.append("")

    for cid in order:
        arr("req_" + cid, req[cid])
        c = cases[cid]
        refusal = 0
        if c["mode"] == "Noisy":
            refusal = 2
        elif c["mode"] == "Legacy" and c["ddecompose"] == "null":
            refusal = 1
        if refusal:
            facts[cid] = []  # the seam never runs for refused requests
        else:
            arr("fact_" + cid, facts[cid])
        if len(req[cid]) != 7:
            sys.exit("case %s: expected 7 req lines, found %d" % (cid, len(req[cid])))
    arr("empty", [])

    out.append("inline const Case* table(std::size_t& count) {")
    out.append("    static const Case kCases[] = {")
    for cid in order:
        c = cases[cid]
        refusal = 0
        if c["mode"] == "Noisy":
            refusal = 2
        elif c["mode"] == "Legacy" and c["ddecompose"] == "null":
            refusal = 1
        out.append('        {"%s", %d, %s, %d, k_req_%s, %d, %s},' %
                   (cid, refusal, cstr(REASONS[refusal]), len(req[cid]), cid,
                    len(facts[cid]),
                    "k_fact_" + cid if facts[cid] else "k_empty"))
    out.append("    };")
    out.append("    count = sizeof(kCases) / sizeof(kCases[0]);")
    out.append("    return kCases;")
    out.append("}")
    out.append("")
    out.append("}  // namespace golden_du")
    out.append("")
    out.append("#endif")

    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    nf = sum(len(facts[c]) for c in order)
    nr = sum(1 for c in order
             if cases[c]["mode"] in ("Noisy",)
             or (cases[c]["mode"] == "Legacy" and cases[c]["ddecompose"] == "null"))
    print("wrote %s: %d cases, %d refusal, %d fact lines" % (dst, len(order), nr, nf))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_decompose_ucarima_golden.py CORPUS_DIR HEADER")
    main(sys.argv[1], sys.argv[2])
