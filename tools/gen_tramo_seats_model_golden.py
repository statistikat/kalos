#!/usr/bin/env python3
"""Generate tests/jvm_tramo_seats_model.h from the item 24-A
tramo-seats-model corpus (validation/evidence/native/tramo-seats-model,
captured by validation/reference/capture-tramo-seats-model.R through the
observer TramoSeatsModelProbe.java against the pinned jdplus 3.9.0 jars;
double capture, byte-identical csv files across JVM processes).

The golden carries, per case: the JVM-echoed request block (req lines, the
frozen SarimaSpec + DecompositionSpec knobs), the 24-A ASSERTABLE fact
grammar (v.* validator facts, the r.* raw-chain structure, the d.decompose
decision, the k.cutOff/k.modelChanged kernel flags when the capture reached
them), the full kernel ProcessingLog stream (kevt) and the status class.
Record-only blocks stay in the csv corpus and are NOT asserted by the
replay: d.* / k.ucar post-allocation values, r c{i} ma/var one-sided facts,
model seasonality and r.excep lines all need the item 24-B spectral
factorization; the two fixMa MatrixException cases and the Noisy-mode NPE
are JVM-observed crashes the unit never reproduces (their status is kept
for documentation).

The replay layer (tests/tramo_seats_model_replay.h) parses the req lines
into kalos::tramo_seats_model_request, runs the unit and compares:
  * every assertable fact line, doubles compared bit for bit (the %.17g
    capture round-trips exactly through strtod);
  * the kevt stream: exact when the live run stayed inside this unit's
    scope, else exact-PREFIX (Legacy + d.decompose null: the live kernel
    continued into DefaultModelApproximator, register D6);
  * the derived flags (approximation_required / seats_exception /
    noisy_model_used / model_changed).
Five cases carry reject=1 (record-only): their live JVM path enters the
Polynomial.roots()/FastEigenValuesSolver QR cascade or the seasonal
root-zone selector reconstruction (bphi stationary parts, degree > 2
minimizer numerators, quarterly degree 4-5 numerators, the bq=2 seasonal
split, the degenerate D2 spectrum w). The unit refuses those inputs
fail-closed (std::invalid_argument), and the replay asserts exactly that
refusal; their captured facts stay in the csv corpus as 24-B evidence.

Regenerate with:
  python3 tools/gen_tramo_seats_model_golden.py \
      validation/evidence/native/tramo-seats-model tests/jvm_tramo_seats_model.h
"""
import csv
import os
import sys

# key == value rows asserted verbatim (values compared as tokens; numeric
# tokens bit-compared by the replay layer).
# Record cases outside the 24-A envelope (see docstring): the unit refuses.
REJECT = {"d_d2", "q_airline", "q_d2", "v_cut_bq2", "v_simplify"}

ASSERT_KEYS = ("v.changed", "v.xl", "v.orders", "v.phi", "v.bphi", "v.theta",
               "v.btheta", "r.decompose", "r.count", "d.decompose",
               "k.cutOff", "k.modelChanged")
# "r" rows: keep only the sar/ur/sfd columns (ma/var need the 24-B factorization).
ASSERT_R_COLS = ("sar", "ur", "sfd")


def cstr(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % o)
    out.append('"')
    return "".join(out)


def main(corpus_dir, dst):
    cases, order = {}, []
    with open(os.path.join(corpus_dir, "cases.csv")) as f:
        for r in csv.DictReader(f):
            cases[r["id"]] = r
            order.append(r["id"])
    req = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "inputs.csv")) as f:
        for r in csv.DictReader(f):
            if r["line"].startswith("req "):
                req[r["id"]].append(r["line"])
    facts = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "model-facts.csv")) as f:
        for r in csv.DictReader(f):
            key, val = r["key"], r["value"]
            if key in ASSERT_KEYS:
                facts[r["id"]].append(key + " " + val if val else key + " ")
            elif key == "r":
                words = val.split()
                if len(words) >= 3 and words[0].startswith("c") \
                        and words[1] in ASSERT_R_COLS:
                    facts[r["id"]].append(key + " " + val)
    events = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "model-events.csv")) as f:
        for r in csv.DictReader(f):
            if r["stream"] != "kevt":
                continue
            events[r["id"]].append("%s %s %s" % (r["kind"], r["depth"], r["msg"]))

    out = []
    out.append("// Generated by tools/gen_tramo_seats_model_golden.py - do not edit.")
    out.append("// Item 24-A tramo-seats-model golden: the double-captured JVM corpus")
    out.append("// (validation/evidence/native/tramo-seats-model) as request-echo, the")
    out.append("// 24-A assertable fact grammar and the kernel event streams. Record-only")
    out.append("// facts (d.*, k.ucar, r ma/var, model seasonality) stay in the csv")
    out.append("// corpus; see the generator docstring for the capture provenance.")
    out.append("#ifndef KALOS_TESTS_JVM_TRAMO_SEATS_MODEL_H")
    out.append("#define KALOS_TESTS_JVM_TRAMO_SEATS_MODEL_H")
    out.append("")
    out.append("#include <cstddef>")
    out.append("")
    out.append("namespace golden_tsm {")
    out.append("")
    out.append("struct Case {")
    out.append("    const char* id;")
    out.append("    const char* status;  // captured status class (record for the JVM crashes)")
    out.append("    const char* mode;    // captured DecompositionSpec mode")
    out.append("    int legacy_approx;   // 1: Legacy and setVarianceMax returned null (D6 prefix)")
    out.append("    int reject;          // 1: QR-cascade record case, refused by the unit (D11)")
    out.append("    std::size_t nreq;")
    out.append("    const char* const* req;")
    out.append("    std::size_t nfacts;")
    out.append("    const char* const* facts;")
    out.append("    std::size_t nevents;")
    out.append("    const char* const* events;")
    out.append("};")
    out.append("")

    def arr(name, items):
        out.append("inline const char* k_%s[] = {" % name)
        if not items:
            # zero-size arrays are not valid C++; the table entry pairs the
            # pointer with length 0, so this sentinel element is never read.
            out.append('    "",')
        for it in items:
            out.append("    %s," % cstr(it))
        out.append("};")
        out.append("")

    for cid in order:
        arr("req_" + cid, req[cid])
        arr("fact_" + cid, facts[cid])
        arr("evt_" + cid, events[cid])
        if len(req[cid]) != 7:
            sys.exit("case %s: expected 7 req lines, found %d" % (cid, len(req[cid])))

    out.append("inline const Case* table(std::size_t& count) {")
    out.append("    static const Case kCases[] = {")
    for cid in order:
        c = cases[cid]
        approx = 1 if (c["mode"] == "Legacy" and c["ddecompose"] == "null") else 0
        out.append('        {"%s", "%s", "%s", %d, %d, %d, k_req_%s, %d, k_fact_%s, %d, k_evt_%s},' %
                   (cid, c["status"], c["mode"], approx,
                    1 if cid in REJECT else 0, len(req[cid]), cid, len(facts[cid]),
                    cid, len(events[cid]), cid))
    out.append("    };")
    out.append("    count = sizeof(kCases) / sizeof(kCases[0]);")
    out.append("    return kCases;")
    out.append("}")
    out.append("")
    out.append("}  // namespace golden_tsm")
    out.append("")
    out.append("#endif")

    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    nf = sum(len(facts[c]) for c in order)
    ne = sum(len(events[c]) for c in order)
    print("wrote %s: %d cases, %d fact lines, %d event lines" % (dst, len(order), nf, ne))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_tramo_seats_model_golden.py CORPUS_DIR HEADER")
    main(sys.argv[1], sys.argv[2])
