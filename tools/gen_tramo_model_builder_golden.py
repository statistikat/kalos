#!/usr/bin/env python3
"""Generate tests/jvm_tramo_model_builder.h from the item 23-A
tramo-model-builder corpus (validation/evidence/native/tramo-model-builder,
captured by validation/reference/capture-tramo-model-builder.R through the
observer TramoModelBuilderProbe.java against the pinned jdplus 3.9.0 jars;
double capture, byte-identical csv files across JVM processes). The golden
is the captured LINE GRAMMAR itself: the oracle protocol lines (src), the
JVM-echoed request block (req), the built ModelDescription facts and the
ProcessingLog events, plus the series values as raw IEEE-754 bits (the
probe's StrictMath series is never re-evaluated in C++). The replay layer
(tests/tramo_model_builder_replay.h) drives kalos::build_tramo_model from
these lines and compares its rendered lines byte for byte. The two
non-monthly record cases carry reject=1: the kalos unit refuses them per
register D11. Regenerate with:
  python3 tools/gen_tramo_model_builder_golden.py \
      validation/evidence/native/tramo-model-builder tests/jvm_tramo_model_builder.h
"""
import csv
import os
import struct
import sys

NAN_BITS = 0x7FF8000000000000


def cstr(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % o)
    out.append('"')
    return "".join(out)


def value_bits(tok):
    if tok == "nan":
        return NAN_BITS
    return struct.unpack(">Q", struct.pack(">d", float(tok)))[0]


def main(corpus_dir, dst):
    cases = {}
    order = []
    with open(os.path.join(corpus_dir, "cases.csv")) as f:
        for r in csv.DictReader(f):
            cases[r["id"]] = r
            order.append(r["id"])
    src, req, values = {i: [] for i in order}, {i: [] for i in order}, {}
    with open(os.path.join(corpus_dir, "inputs.csv")) as f:
        for r in csv.DictReader(f):
            line = r["line"]
            if line.startswith("src "):
                src[r["id"]].append(line)
            elif line.startswith("req "):
                req[r["id"]].append(line)
            elif line.startswith("values "):
                values[r["id"]] = [value_bits(t) for t in line[len("values "):].split(";")]
    facts = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "builder-facts.csv")) as f:
        for r in csv.DictReader(f):
            if r["key"] == "case":
                continue
            facts[r["id"]].append(r["key"] + " " + r["value"])
    events = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "builder-events.csv")) as f:
        for r in csv.DictReader(f):
            if r["depth"] != "0" or r["detail"] != "-":
                sys.exit("event detail/depth outside the renderable envelope: " + r["id"])
            events[r["id"]].append(r["kind"] + " " + r["msg"])

    out = []
    out.append("// Generated by tools/gen_tramo_model_builder_golden.py - do not edit.")
    out.append("// Item 23-A tramo-model-builder golden: the double-captured JVM corpus")
    out.append("// (validation/evidence/native/tramo-model-builder) as captured protocol,")
    out.append("// request-echo, fact and event lines plus the raw IEEE-754 bits of each")
    out.append("// case series. See the generator docstring for the capture command.")
    out.append("#ifndef KALOS_TESTS_JVM_TRAMO_MODEL_BUILDER_H")
    out.append("#define KALOS_TESTS_JVM_TRAMO_MODEL_BUILDER_H")
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace golden_tmb {")
    out.append("")
    out.append("struct Case {")
    out.append("    const char* id;")
    out.append("    int reject;  // 1: non-monthly record case, refused by the unit (D11)")
    out.append("    std::size_t nlines;")
    out.append("    const char* const* lines;")
    out.append("    std::size_t nreq;")
    out.append("    const char* const* req;")
    out.append("    std::size_t nvalues;")
    out.append("    const std::uint64_t* values;")
    out.append("    std::size_t nfacts;")
    out.append("    const char* const* facts;")
    out.append("    std::size_t nevents;")
    out.append("    const char* const* events;")
    out.append("};")
    out.append("")

    def arr(name, ctype, items, fmt):
        out.append("inline const %s k_%s[] = {" % (ctype, name))
        if not items:
            # zero-size arrays are not valid C++; the table entry pairs the
            # pointer with length 0, so this sentinel element is never read.
            out.append('    "%s",' % "" if ctype == "char*" else "    0,")
        for it in items:
            out.append("    %s," % fmt(it))
        out.append("};")
        out.append("")

    for cid in order:
        if cid not in values:
            sys.exit("case %s has no values line" % cid)
        arr("line_" + cid, "char*", src[cid], cstr)
        arr("req_" + cid, "char*", req[cid], cstr)
        arr("val_" + cid, "std::uint64_t", values[cid], lambda v: "0x%016xULL" % v)
        arr("fact_" + cid, "char*", facts[cid], cstr)
        arr("evt_" + cid, "char*", events[cid], cstr)

    out.append("inline const Case* table(std::size_t& count) {")
    out.append("    static const Case kCases[] = {")
    for cid in order:
        reject = "1" if cases[cid]["freq"] != "12" else "0"
        out.append('        {"%s", %s, %d, k_line_%s, %d, k_req_%s, %d, k_val_%s, %d, '
                   "k_fact_%s, %d, k_evt_%s}," %
                   (cid, reject, len(src[cid]), cid, len(req[cid]), cid,
                    len(values[cid]), cid, len(facts[cid]), cid, len(events[cid]), cid))
    out.append("    };")
    out.append("    count = sizeof(kCases) / sizeof(kCases[0]);")
    out.append("    return kCases;")
    out.append("}")
    out.append("")
    out.append("}  // namespace golden_tmb")
    out.append("")
    out.append("#endif")

    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s: %d cases" % (dst, len(order)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_tramo_model_builder_golden.py CORPUS_DIR HEADER")
    main(sys.argv[1], sys.argv[2])
