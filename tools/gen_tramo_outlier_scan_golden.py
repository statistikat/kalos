#!/usr/bin/env python3
"""Generate tests/jvm_tramo_outlier_scan.h from the item 23-B round-0
outlier-scan corpus (validation/evidence/native/tramo-outlier-scan, captured
through the observer TramoOutlierScanProbe.java against the pinned jdplus
3.9.0 jars; double capture, byte-identical csv files across JVM processes).
The golden is the captured LINE GRAMMAR itself: the oracle protocol lines
(SCAN header), the JVM-echoed request block (req), the probe fact lines (in,
pre_vars, estdom, scan_status, after_vars, need_estimation, spec_after) and
the ProcessingLog events, plus the raw IEEE-754 bits of each case series.
The replay layer (tests/test_tramo_outlier_scan.cpp) drives
kalos::scan_tramo_outliers from the header tokens and compares the decision
status and the first selected [position, type] pair against the captured
module facts; the so and spanout cases carry divergent=1 because the live
multi-round driver later empties their selection (round-0 stop gate, D3
evidence) and the replay there pins only the request echoes; pexao47 carries
seam_throw because the JVM reaches its observation through warm re-estimation
on a non-constant design, which the qualified Levenberg-Marquardt seam fails
closed on. Regenerate with:
  python3 tools/gen_tramo_outlier_scan_golden.py \
      validation/evidence/native/tramo-outlier-scan tests/jvm_tramo_outlier_scan.h
"""
import csv
import os
import struct
import sys

NAN_BITS = 0x7FF8000000000000

# The live multi-round driver removes the round-0 pick before the module
# reads the set: the final status diverges from the round-0 observation.
DIVERGENT = {"sc_so", "sc_spanout"}

# Constructions whose round-0 observation the JVM reaches through warm
# re-estimation (a non-invertible HannanRissanen landing combined with a
# non-constant regression design). The warm Levenberg-Marquardt seam is
# qualified for design-free / constant-column designs only, so the unit fails
# closed there with the message below instead of approximating the machine.
SEAM_THROW = {
    "sc_pexao47": "scan_tramo_outliers: warm re-estimation with non-constant "
                  "designs is outside the qualified seam",
}


def cstr(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % o)
    out.append('"')
    return "".join(out)


def value_bits(tok):
    if tok == "nan":
        return NAN_BITS
    return struct.unpack(">Q", struct.pack(">d", float(tok)))[0]


def render_event(r):
    kind = r["kind"]
    if r["detail"] != "-":
        return " ".join([kind, r["detail"]])
    if r["msg"] != "-":
        return " ".join([kind, r["msg"]])
    return kind


def main(corpus_dir, dst):
    cases = {}
    order = []
    with open(os.path.join(corpus_dir, "cases.csv")) as f:
        for r in csv.DictReader(f):
            cases[r["id"]] = r
            order.append(r["id"])
    src, req, values = {i: [] for i in order}, {i: [] for i in order}, {}
    with open(os.path.join(corpus_dir, "inputs.csv")) as f:
        for r in csv.DictReader(f):
            line = r["line"]
            if line.startswith("values "):
                values[r["id"]] = [value_bits(t) for t in line[len("values "):].split()]
            elif line.startswith("req "):
                req[r["id"]].append(line)
            else:
                src[r["id"]].append(line)
    facts = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "scan-facts.csv")) as f:
        for r in csv.DictReader(f):
            if r["key"] == "case":
                continue
            facts[r["id"]].append(r["key"] + " " + r["value"])
    events = {i: [] for i in order}
    with open(os.path.join(corpus_dir, "scan-events.csv")) as f:
        for r in csv.DictReader(f):
            if r["depth"] not in ("0", "1"):
                sys.exit("event depth outside the renderable envelope: " + r["id"])
            events[r["id"]].append(render_event(r))

    out = []
    out.append("// Generated by tools/gen_tramo_outlier_scan_golden.py - do not edit.")
    out.append("// Item 23-B round-0 outlier-scan golden: the double-captured JVM corpus")
    out.append("// (validation/evidence/native/tramo-outlier-scan) as captured protocol,")
    out.append("// request-echo, fact and event lines plus the raw IEEE-754 bits of each")
    out.append("// case series. See the generator docstring for the capture command.")
    out.append("#ifndef KALOS_TESTS_JVM_TRAMO_OUTLIER_SCAN_H")
    out.append("#define KALOS_TESTS_JVM_TRAMO_OUTLIER_SCAN_H")
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace golden_tos {")
    out.append("")
    out.append("struct Case {")
    out.append("    const char* id;")
    out.append("    int divergent; // 1: multi-round removes the round-0 pick (D3 evidence)")
    out.append("    const char* status;  // captured ProcessingResult name")
    out.append("    const char* outliers; // captured first-entry grammar \"[p, t],...\"")
    out.append("    const char* seam_throw; // non-empty: the pinned seam fails closed")
    out.append("    std::size_t nlines;")
    out.append("    const char* const* lines;")
    out.append("    std::size_t nreq;")
    out.append("    const char* const* req;")
    out.append("    std::size_t nvalues;")
    out.append("    const std::uint64_t* values;")
    out.append("    std::size_t nfacts;")
    out.append("    const char* const* facts;")
    out.append("    std::size_t nevents;")
    out.append("    const char* const* events;")
    out.append("};")
    out.append("")

    def arr(name, ctype, items, fmt):
        out.append("inline const %s k_%s[] = {" % (ctype, name))
        if not items:
            out.append('    "%s",' % "" if ctype == "char*" else "    0,")
        for it in items:
            out.append("    %s," % fmt(it))
        out.append("};")
        out.append("")

    for cid in order:
        arr("line_" + cid, "char*", src[cid], cstr)
        arr("req_" + cid, "char*", req[cid], cstr)
        arr("val_" + cid, "std::uint64_t", values.get(cid, []), lambda v: "0x%016xULL" % v)
        arr("fact_" + cid, "char*", facts[cid], cstr)
        arr("evt_" + cid, "char*", events[cid], cstr)

    out.append("inline const Case* table(std::size_t& count) {")
    out.append("    static const Case kCases[] = {")
    for cid in order:
        c = cases[cid]
        out.append("        {%s, %d, %s, %s, %s, %d, k_line_%s, %d, k_req_%s, %d, k_val_%s, %d,"
                   " k_fact_%s, %d, k_evt_%s}," % (
                       cstr(cid), 1 if cid in DIVERGENT else 0,
                       cstr(c["status"]), cstr(c["outliers"]),
                       cstr(SEAM_THROW.get(cid, "")),
                       len(src[cid]), cid, len(req[cid]), cid,
                       len(values.get(cid, [])), cid,
                       len(facts[cid]), cid, len(events[cid]), cid))
    out.append("    };")
    out.append("    count = sizeof(kCases) / sizeof(kCases[0]);")
    out.append("    return kCases;")
    out.append("}")
    out.append("")
    out.append("} // namespace golden_tos")
    out.append("")
    out.append("#endif")
    out.append("")

    with open(dst, "w") as f:
        f.write("\n".join(out))
    print("wrote %s (%d cases)" % (dst, len(order)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
