#!/usr/bin/env python3
"""Generate tests/jvm_tramo_battery.h from the item 23-C.2 tramo
differencing-BATTERY corpus (validation/evidence/native/tramo-differencing-
battery, captured through the observer TramoBatteryProbe.java against the
pinned jdplus 3.9.0 jars; double capture byte-identical across JVM
processes, class-load witnesses under loadlog-*.txt proving the battery
classes plus SpectralPeaks and SeasonalOverDifferencingTest execute).

The golden is the captured LINE GRAMMAR itself: the case header (BAT), the
raw value tokens, and every JVM-echoed fact line (state/coef/resid/lin/lser/
mstat/ftest/ctlst/resl/over/cand/step/seas1/seas2/final/estimate/init/
cleanup/diff_*). The replay layer (tests/test_tramo_differencing_battery.cpp)
drives kalos::decide_tramo_differencing_battery from the per-case pinned
state panels and asserts every decision line (seas1, step x 4, seas2,
final), the per-state ports (F p-value bits through the incBeta kernel, the
residual-ladder score, the spectral-peaks gate, the
SeasonalOverDifferencingTest code) and the candidate-construction stream.
Regenerate with:
  python3 tools/gen_tramo_battery_golden.py \
      validation/evidence/native/tramo-differencing-battery tests/jvm_tramo_battery.h
"""
import csv
import os
import struct
import sys

NAN_BITS = 0x7FF8000000000000


def cstr(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\x%02x" % o)
    out.append('"')
    return "".join(out)


def value_bits(tok):
    if tok == "nan":
        return NAN_BITS
    return struct.unpack(">Q", struct.pack(">d", float(tok)))[0]


def main(corpus_dir, dst):
    headers = {}
    series = {}
    order = []
    with open(os.path.join(corpus_dir, "inputs.csv")) as f:
        for r in csv.DictReader(f):
            line = r["line"]
            if line.startswith("req "):
                continue
            tok = line.split(" ")
            cid = r["id"]
            if tok[0] == "BAT":
                if cid not in headers:
                    headers[cid] = tok
                    order.append(cid)
            elif tok[0] == "values":
                series[cid] = [value_bits(t) for t in tok[1:]]

    facts = {}
    with open(os.path.join(corpus_dir, "diff-facts.csv")) as f:
        for r in csv.DictReader(f):
            facts.setdefault(r["id"], []).append((r["key"], r["value"]))

    meta = {}
    with open(os.path.join(corpus_dir, "metadata.R")) as f:
        for line in f:
            if " <- " in line:
                k, v = line.strip().split(" <- ", 1)
                meta[k] = v.strip().strip('"')

    out = []
    out.append("// Generated by tools/gen_tramo_battery_golden.py - do not edit.")
    out.append("// Item 23-C.2 tramo differencing-battery golden: the live")
    out.append("// SeasonalityController / RegularUnder(+2) / SeasonalUnder(+2)")
    out.append("// battery, the SeasonalOverDifferencingTest over-side and the")
    out.append("// SeasonalityTests/SpectralPeaks stage facts captured through")
    out.append("// validation/reference/TramoBatteryProbe.java from the pinned")
    out.append("// jdplus 3.9.0 jars (corpus validation/evidence/native/")
    out.append("// tramo-differencing-battery, double capture byte-identical;")
    out.append("// the F-kernel corpus triples replay through")
    out.append("// validation/reference/fcdf_golden.txt).")
    out.append("// jvm = %s" % meta.get("capture_jvm", "?"))
    out.append("// cases = %s (replayed %s, changed %s), facts = %s, cands = %s"
               % (meta.get("n_cases", "?"), meta.get("replayed", "?"),
                  meta.get("changed_cases", "?"), meta.get("n_facts", "?"),
                  meta.get("n_cands", "?")))
    out.append("// sodt_loads = %s, spectralpeaks_loads = %s (loadwitness.csv)"
               % (meta.get("sodt_loads", "?"), meta.get("spectralpeaks_loads", "?")))
    out.append("#ifndef KALOS_TESTS_JVM_TRAMO_BATTERY_H")
    out.append("#define KALOS_TESTS_JVM_TRAMO_BATTERY_H")
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace kalos::test {")
    out.append("")
    out.append("struct TbCase {")
    out.append("    const char* id;")
    out.append("    int period;")
    out.append("    int seasonal;       // ctx.seasonal entry flag")
    out.append("    int ost;            // ctx.originalSeasonalityTest entry value")
    out.append("    int log_input;      // description log flag")
    out.append("    int d0, bd0, p0, q0, bp0, bq0;  // entry description orders")
    out.append("    int mean0;          // entry description mean flag")
    out.append("    const std::uint64_t* series_bits;")
    out.append("    std::size_t series_len;")
    out.append("    const char* const* facts;       // every fact line, capture order")
    out.append("    std::size_t facts_len;")
    out.append("};")
    out.append("")

    n_series = 0
    for cid in order:
        tok = headers[cid]
        # BAT id freq seasonal ost log d bd p q bp bq mean cancel ub1 ub2 eps
        # ip initial io ao ls tc so tcrate ml curva sweep
        out.append("static const std::uint64_t kSeries_%s[] = {%s};"
                   % (cid, ", ".join("0x%016xULL" % b for b in series[cid])))
        n_series += len(series[cid])
        lines = ["%s %s" % (k, v) for (k, v) in facts[cid]]
        out.append("static const char* const kFacts_%s[] = {%s};"
                   % (cid, " ".join(cstr(l) + "," for l in lines)))

    out.append("static const TbCase kTbCases[] = {")
    for cid in order:
        tok = headers[cid]
        yes = lambda i: 1 if tok[i] == "y" else 0
        out.append("    {%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, "
                   "kSeries_%s, %d, kFacts_%s, %d},"
                   % (cstr(cid), tok[2], yes(3), tok[4], yes(5),
                      tok[6], tok[7], tok[8], tok[9], tok[10], tok[11],
                      yes(12), cid, len(series[cid]), cid, len(facts[cid])))
    out.append("};")
    out.append("")
    out.append("inline const TbCase* cases(std::size_t& count) {")
    out.append("    count = sizeof(kTbCases) / sizeof(kTbCases[0]);")
    out.append("    return kTbCases;")
    out.append("}")
    out.append("")
    out.append("}  // namespace kalos::test")
    out.append("")
    out.append("#endif")

    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s (%d cases, %d facts, %d series values)"
          % (dst, len(order), sum(len(v) for v in facts.values()), n_series))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
