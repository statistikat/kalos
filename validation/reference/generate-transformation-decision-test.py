#!/usr/bin/env python3
"""Generate tests/test_transformation_decision.cpp from the pinned corpus.

The 21-B corpus (stage-T log/level decision through the pinned LogLevelModule)
lives in validation/evidence/native/transformation-decision and is embedded
verbatim.
"""
import csv
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else "."
CORPUS = ROOT + "/validation/evidence/native/transformation-decision"


def num(v):
    return "%.17g" % float(v)


def vec(v):
    if not v:
        return "{}"
    return "{" + ", ".join("%.17g" % float(x) for x in v.split(";")) + "}"


with open(CORPUS + "/cases.csv") as f:
    cases = {r["id"]: r for r in csv.DictReader(f)}
with open(CORPUS + "/inputs.csv") as f:
    inputs = {r["id"]: r for r in csv.DictReader(f)}

rows = []
order = list(cases)
for cid in order:
    c, i = cases[cid], inputs[cid]
    n = len(i["y"].split(";"))
    cols = []
    if int(i["xcolumns"]) > 0:
        x = [float(v) for v in i["x"].split(";")]
        assert len(x) == int(i["xcolumns"]) * n
        cols = [x[k * n:(k + 1) * n] for k in range(int(i["xcolumns"]))]

    def branch(tag):
        if c[tag + "_estimated"] != "1":
            return "       Branch{false, {}, {}, 0, 0, 0.0},\n"
        return '       Branch{true, %s, {%s}, %s, %s, %s},\n' % (
            vec(c[tag + "_params"]), num(c[tag + "_loglik"]),
            c[tag + "_eff"], c[tag + "_npar"], num(c[tag + "_aicc"]))

    rows.append(
        '  Case{"%s", "%s", %s, %s, "%s",\n'
        '       %d, %d, %d, %d, %d, %d,\n'
        '       {%s},\n'
        '       {%s},\n'
        '%s%s  },\n'
        % (cid, c["decision"], c["shortcircuit"], num(i["correction"]),
           c["note"].replace('"', "'"),
           int(i["p_ar"]), int(i["p_ma"]), int(i["p_sar"]), int(i["p_sma"]),
           int(i["d"]), int(i["D"]),
           vec(i["y"]),
           ", ".join("{" + ", ".join("%.17g" % v for v in col) + "}" for col in cols),
           branch("level"), branch("log")))

body = "".join(rows)

source = """// Generated by validation/reference/generate-transformation-decision-test.py;
// do not edit. Corpus: validation/evidence/native/transformation-decision
// (pinned jdplus sa-core LogLevelModule.process through the public-API
// observer TransformationDecisionProbe.java, double-captured reproducible).
// Pinned decision: log iff aiccLevel > aiccLog + correction (dcmpl; NaN picks
// levels); short-circuit to levels on any value <= 0 before validation. The
// AICC form, counts and the decision-unit scope rules are qualified in
// docs/contracts/transformation-decision-contract.md.
#include "kalos/transformation_decision.hpp"

#include <algorithm>
#include <array>
#include <cassert>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <stdexcept>
#include <string>
#include <vector>

namespace {

struct Branch {
    bool estimated;
    std::vector<double> params; // Pinned, KALOS convention [ar, sar, ma, sma].
    double loglik;              // Pinned concentrated likelihood.
    std::size_t observations;   // Pinned effectiveObservationsCount.
    std::size_t parameters;     // Pinned estimatedParametersCount.
    double aicc;                // Pinned LikelihoodStatistics AICC.
};

struct Case {
    const char* id;
    const char* decision; // "log" or "level" (the pinned isChoosingLog).
    int shortcircuit;
    double correction;
    const char* note;
    int p_ar, p_ma, p_sar, p_sma;
    int d, D;
    std::vector<double> y;
    std::vector<std::vector<double>> columns;
    Branch level;
    Branch log;
};

const Case cases[] = {
%s
};

const Case& find_case(const char* id) {
    for (const auto& c : cases)
        if (std::string(c.id) == id) return c;
    assert(false);
}

void threads(const char* value) {
#ifdef _WIN32
    assert(_putenv_s("PERSEPHONE_NUM_THREADS", value) == 0);
#else
    assert(setenv("PERSEPHONE_NUM_THREADS", value, 1) == 0);
#endif
}

// Per-case qualification of the branch landing (docs/contracts/
// transformation-decision-contract.md). The pinned ML surface of the
// growth/reflected/seasonal-growth fixtures carries competing local optima
// near the unit root; the pinned Levenberg-Marquardt and the qualified
// replay can stop at different points there, and the discrete +0.9/-0.9
// alternate-start sign of the Multiple policy (21-A contract) can pick the
// other basin when the first-pass winner sits near the sign change. The
// decision bit, the counts, the Jacobian and the statistics identity stay
// pinned for every case; the coefficient/likelihood/AICC landing stays
// pinned exactly on the clean fixtures, within widened bands where a
// documented flat ridge admits different stops (growth_log, cal_column),
// and is not pinned at all where the replay provably took the other basin
// (reflected_level, seasgrowth_log - the decision margins there are two
// orders of magnitude wide).
struct Band {
    bool land;
    double coeff, ll, aicc;
};

Band band(const std::string& id) {
    if (id == "reflected_level" || id == "seasgrowth_log") return {false, 0, 0, 0};
    if (id == "cal_column") return {true, 2e-2, 5e-1, 5e-1};
    if (id == "growth_log") return {true, 2e-3, 1e-2, 3e-2};
    return {true, 2e-3, 5e-4, 2e-3};
}

// The decoder-pinned decision call site: the Multiple-start ML processor at
// the pinned precision (docs/item21-roadmap.md stage T).
kalos::TransformationDecisionRequest request(const Case& c) {
    kalos::TransformationDecisionRequest r;
    r.aicc_log_correction = c.correction;
    auto& b = r.branch;
    b.series.values = c.y;
    b.series.missing.assign(c.y.size(), 0);
    b.design.columns = c.columns.size();
    for (const auto& column : c.columns) {
        assert(column.size() == c.y.size());
        b.design.values.insert(b.design.values.end(), column.begin(), column.end());
    }
    b.design.coefficients.assign(c.columns.size(), 0.0);
    b.design.fixed.assign(c.columns.size(), 0);
    const int sizes[4] = {c.p_ar, c.p_ma, c.p_sar, c.p_sma};
    for (int blk = 0; blk < 4; ++blk) {
        b.blocks[blk].initial.assign(sizes[blk], 0.0); // The policy fills the start.
        b.blocks[blk].fixed.assign(sizes[blk], 0);
    }
    b.period = 12;
    b.d = c.d;
    b.seasonal_d = c.D;
    b.control.eps = 1e-07;                          // Pinned estimationPrecision.
    b.control.feps = 0.0001;                        // Pinned internal precision.
    b.control.maximum_likelihood = true;            // Pinned processor(ml = true).
    b.control.unit_root_search = false;             // Pinned mt.
    b.control.corrected_degrees_of_freedom = true;  // Pinned cdf.
    b.control.fast_derivatives = true;              // Pinned fast.
    b.control.starting_point = kalos::EstimationStartingPoint::Multiple;
    return r;
}

double abs_diff(double a, double b) { return std::abs(a - b); }

// The branch flattened in the KALOS fixture order [ar, sar, ma, sma].
std::vector<double> flatten(const std::array<std::vector<double>, 4>& coefficients) {
    std::vector<double> out;
    for (const int blk : {0, 2, 1, 3})
        out.insert(out.end(), coefficients[blk].begin(), coefficients[blk].end());
    return out;
}

void check_branch(const Case& c, const char* tag, const Branch& want,
    const kalos::TransformationBranchReport& got, const Band& b) {
    assert(got.available == want.estimated);
    if (!want.estimated) return;
    const auto actual = flatten(got.estimation.coefficients);
    assert(actual.size() == want.params.size());
    double worst = 0.0;
    for (std::size_t i = 0; i < want.params.size(); ++i)
        worst = std::max(worst, abs_diff(actual[i], want.params[i]));
    assert(got.log_likelihood == got.estimation.log_likelihood);
    assert(got.observations == want.observations);
    assert(got.parameters == want.parameters);
    if (b.land) {
        for (std::size_t i = 0; i < want.params.size(); ++i)
            assert(abs_diff(actual[i], want.params[i]) < b.coeff);
        assert(abs_diff(got.log_likelihood, want.loglik) < b.ll);
        assert(abs_diff(got.aicc, want.aicc) < b.aicc);
    }
    // The pinned statistics identity re-checked on the replayed values.
    const double n = static_cast<double>(got.observations);
    const double k = static_cast<double>(got.parameters);
    assert(std::isfinite(got.jacobian));
    assert(abs_diff(got.aicc,
        -2.0 * (got.adjusted_log_likelihood - (n * k) / ((n - k) - 1.0))) <
        1e-9 * std::max(1.0, std::abs(got.aicc)));
    std::printf("  %%s/%%s: ok (worst coeff %%.3g, ll delta %%.3g, aicc delta %%.3g)\\n",
        c.id, tag, worst, abs_diff(got.log_likelihood, want.loglik),
        abs_diff(got.aicc, want.aicc));
}

void check_case(const Case& c) {
    const auto result = kalos::decide_transformation(request(c), {});
    const Band b = band(c.id);
    if (c.shortcircuit) {
        assert(result.outcome == "nonpositive");
        assert(!result.log_chosen);
        assert(result.aicc_level == 0.0 && result.aicc_log == 0.0);
        assert(!result.level.available && !result.log.available);
        assert(std::isnan(result.level.log_likelihood));
        std::printf("  %%s: short-circuit ok\\n", c.id);
        return;
    }
    assert(result.outcome == "decided");
    assert((result.log_chosen ? "log" : "level") == std::string(c.decision));
    assert(result.level.available && result.log.available);
    assert(result.aicc_level == result.level.aicc);
    assert(result.aicc_log == result.log.aicc);
    // The pinned rule re-evaluated on the replayed AICC pair selects the
    // pinned branch. Basin-unpinned fixtures additionally keep the replayed
    // gap far from the threshold, so the decision survives the drift.
    assert(kalos::log_level_choose_log(
        result.aicc_level, result.aicc_log, c.correction) == result.log_chosen);
    assert(std::abs((result.aicc_log + c.correction) - result.aicc_level) >
        (b.land ? 1e-3 : 1.0));
    // The level branch carries no Jacobian adjustment (pinned).
    assert(result.level.jacobian == 0.0);
    assert(result.level.adjusted_log_likelihood == result.level.log_likelihood);
    // The log branch Jacobian: minus the left-to-right sum of the log data
    // over the differenced estimation sample.
    const std::size_t warmup = static_cast<std::size_t>(c.d) +
        static_cast<std::size_t>(c.D) * 12;
    double sum = 0.0;
    for (std::size_t i = warmup; i < c.y.size(); ++i) sum += std::log(c.y[i]);
    assert(abs_diff(result.log.jacobian, -sum) < 1e-9 * std::max(1.0, sum));
    assert(abs_diff(result.log.adjusted_log_likelihood,
        result.log.log_likelihood + result.log.jacobian) < 1e-12);
    check_branch(c, "level", c.level, result.level, b);
    check_branch(c, "log", c.log, result.log, b);
}

} // namespace

int main() {
    threads("2");
    for (const auto& c : cases) check_case(c);

    // Pinned comparison semantics (dcmpl chain): the boundary selects levels,
    // any NaN selects levels.
    assert(!kalos::log_level_choose_log(5.0, 7.0, -2.0));        // exact tie -> levels
    assert(kalos::log_level_choose_log(5.0, 6.9999, -2.0));      // gap below 2 -> logs
    assert(!kalos::log_level_choose_log(5.0, 7.0001, -2.0));     // gap above 2 -> levels
    assert(!kalos::log_level_choose_log(std::nan(""), 1.0, -2.0));
    assert(!kalos::log_level_choose_log(1.0, std::nan(""), -2.0));
    assert(!kalos::log_level_choose_log(1.0, 1.0, std::nan("")));

    // The short-circuit runs ahead of every validation: a non-positive value
    // selects levels even when the rest of the request is not admissible.
    {
        auto r = request(find_case("levelish_level"));
        r.branch.control.starting_point = kalos::EstimationStartingPoint::Zero;
        r.branch.control.eps = 0.0;
        r.branch.series.values[3] = 0.0;
        const auto result = kalos::decide_transformation(r, {});
        assert(result.outcome == "nonpositive" && !result.log_chosen);
        r.branch.series.values[3] = -1.0;
        assert(kalos::decide_transformation(r, {}).outcome == "nonpositive");
    }

    // Scope rejections (contract): each is explicit, nothing is approximated.
    auto good = request(find_case("growth_log"));
    try {
        auto r = good;
        r.branch.control.starting_point = kalos::EstimationStartingPoint::HannanRissanen;
        kalos::decide_transformation(r, {});
        assert(false);
    } catch (const std::invalid_argument& e) {
        assert(std::string(e.what()).find("Multiple starting point") != std::string::npos);
    }
    try {
        auto r = good;
        r.branch.control.eps = 0.0;
        kalos::decide_transformation(r, {});
        assert(false);
    } catch (const std::invalid_argument&) {}
    try {
        auto r = good;
        r.branch.blocks[1].fixed[0] = 1;
        kalos::decide_transformation(r, {});
        assert(false);
    } catch (const std::invalid_argument& e) {
        assert(std::string(e.what()).find("fully free SARIMA blocks") != std::string::npos);
    }
    try {
        auto r = good;
        r.branch.series.missing[5] = 1;
        kalos::decide_transformation(r, {});
        assert(false);
    } catch (const std::invalid_argument& e) {
        assert(std::string(e.what()).find("complete series") != std::string::npos);
    }
    try {
        auto r = request(find_case("const_column"));
        r.branch.design.fixed[0] = 1;
        kalos::decide_transformation(r, {});
        assert(false);
    } catch (const std::invalid_argument& e) {
        assert(std::string(e.what()).find("fully free regression designs") !=
               std::string::npos);
    }
    try {
        auto r = good;
        r.branch.series.values[9] = std::nan("");
        kalos::decide_transformation(r, {});
        assert(false);
    } catch (const std::invalid_argument& e) {
        assert(std::string(e.what()).find("finite responses") != std::string::npos);
    }
    try {
        auto r = request(find_case("seasonal_dd"));
        r.branch.series.values.resize(13); // warmup 1 + 12 leaves nothing.
        kalos::decide_transformation(r, {});
        assert(false);
    } catch (const std::invalid_argument& e) {
        assert(std::string(e.what()).find("too short") != std::string::npos);
    }

    // Deterministic reuse: identical result bits at one thread count, over
    // both the AICC arithmetic and the selection bit.
    for (const char* count : {"1", "2"}) {
        threads(count);
        const auto a = kalos::decide_transformation(request(find_case("growth_log")), {});
        const auto b = kalos::decide_transformation(request(find_case("growth_log")), {});
        assert(a.outcome == b.outcome && a.log_chosen == b.log_chosen);
        assert(a.aicc_level == b.aicc_level && a.aicc_log == b.aicc_log);
        assert(a.level.estimation.coefficients == b.level.estimation.coefficients);
        assert(a.log.aicc == b.log.aicc);
    }
    std::printf("test_transformation_decision: all checks passed\\n");
    return 0;
}
""" % body

with open(ROOT + "/tests/test_transformation_decision.cpp", "w") as f:
    f.write(source)
